let lang = 'en';
try {
  const saved = localStorage.getItem('lang'), nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  lang = D[saved] ? saved : D[nav] ? nav : 'en';
} catch { /* storage blocked: stay on English */ }

const listeners = [];
export const getLang = () => lang;
export const t = (k) => D[lang]?.[k] ?? D.en[k] ?? k;
export const onLang = (fn) => listeners.push(fn);

export function applyDom() {
  const root = document.documentElement;
  root.lang = lang; root.dir = RTL.has(lang) ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.title = t('doc_title');
  listeners.forEach((fn) => fn(lang));
}
export function setLang(next) {
  if (!D[next]) return;
  lang = next; try { localStorage.setItem('lang', next); } catch { /* ignore */ }
  applyDom();
}
// Set direction immediately so the loading screen is already correct.
document.documentElement.lang = lang; document.documentElement.dir = RTL.has(lang) ? 'rtl' : 'ltr';
